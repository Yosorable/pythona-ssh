const requested = (window.PYTHONA_SSH?.language || new URLSearchParams(location.search).get("lang") || "en").replaceAll("_", "-").toLowerCase();
export const language = requested.startsWith("zh")
  ? (/hant|-(tw|hk|mo)/.test(requested) ? "zh-Hant" : "zh-Hans") : "en";
const catalog = language === "zh-Hans" ? zhHans : language === "zh-Hant" ? zhHant : en;
export const t = (key: Key): string => catalog[key];
export function errorText(error: unknown): string {
  if (!error) return "";
  const item = error as AppError;
  const message = item.code && item.code in catalog ? catalog[item.code as Key] : item.code || t("operation_failed");
  return message + (item.detail ? " " + item.detail : "");
}
