const catalogs = { en, "zh-Hans": zhHans, "zh-Hant": zhHant, "pt-BR": ptBR, ja, ko, de, fr, es, ru };
type Language = keyof typeof catalogs;

function resolveLanguage(requested: string): Language {
  const normalized = requested.replaceAll("_", "-").toLowerCase();
  if (normalized.startsWith("zh")) return /hant|-(tw|hk|mo)/.test(normalized) ? "zh-Hant" : "zh-Hans";
  if (normalized === "pt" || normalized === "pt-br" || normalized.startsWith("pt-br-")) return "pt-BR";
  const base = normalized.split("-")[0];
  return Object.hasOwn(catalogs, base) ? base as Language : "en";
}

export const language = resolveLanguage(window.PYTHONA_SSH?.language || new URLSearchParams(location.search).get("lang") || "en");
const catalog = catalogs[language];
export const t = (key: Key): string => catalog[key];
export function errorText(error: unknown): string {
  if (!error) return "";
  const item = error as AppError;
  const message = item.code && item.code in catalog ? catalog[item.code as Key] : item.code || t("operation_failed");
  return message + (item.detail ? " " + item.detail : "");
}
